class PandemoniumLocationCategory(IntEnum):
    PROGRESSION = 0
    EVENT = 1
    LEVEL_CLEAR = 2
    RACE_CLEAR = 3
    PINBALL_CLEAR = 4
    LEVEL_PERCENTAGE = 5
    ENEMY_KILL = 6
    TRANSFORM_GATE = 7
    CHARACTER_CLEAR = 8


class PandemoniumLocationData(NamedTuple):
    name: str
    default_item: str
    category: PandemoniumLocationCategory


class PandemoniumLocation(Location):
    game: str = "Pandemonium"
    category: PandemoniumLocationCategory
    default_item_name: str

    def __init__(
        self,
        player: int,
        name: str,
        category: PandemoniumLocationCategory,
        default_item_name: str,
        address: Optional[int] = None,
        parent: Optional[Region] = None,
    ):
        super().__init__(player, name, address, parent)
        self.default_item_name = default_item_name
        self.category = category
        self.name = name

    @staticmethod
    def get_name_to_id() -> dict:
        base_id = 99270000
        region_offset = 1000
        table_order = [
            "Menu",
            "Map",
            "Skull Fortress",
            "Hollow Stairway",
            "Dungeon Tower",
            "Lost Caves",
            "Fungus Grotto",
            "Acid Pools",
            "Shroom Lord",
            "Burning Desert",
            "Branky Wastes",
            "Spider Forest",
            "Canopy Village",
            "Soldier Barracks",
            "Honcho's Logmill",
            "Goon Honcho",
            "Honcho's Airship",
            "Dragoon Skyfort",
            "Cloud Citadel",
            "Efreet Palace",
            "Frozen Cavern",
            "Storm Temple",
            "The Wishing Engine",
        ]

        output = {}
        for i, region_name in enumerate(table_order):
            current_region_base_id = base_id + (i * region_offset)
            for j, location_data in enumerate(location_tables[region_name]):
                if location_data.category != PandemoniumLocationCategory.EVENT:
                    output[location_data.name] = current_region_base_id + j

        return output

    def place_locked_item(self, item: PandemoniumItem):
        self.item = item
        self.locked = True
        item.location = self


